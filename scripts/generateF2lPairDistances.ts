import * as fs from 'fs';
import * as path from 'path';
import { applyMove, crossSolved, topLayerPlacementIndex, type Facelets } from '../composables/recon/f2lIntuitiveDetection';
import type { Color } from '../composables/recon/SimpleCube';

const SEARCH_DEPTH = 4;
const CORNER_PLACEMENTS = 12;
const EDGE_PLACEMENTS = 8;
const OUTPUT_PATH = path.join(__dirname, '../composables/recon/f2lPairDistances.ts');

const SEARCH_TOKENS = ['U', 'R', 'L', 'F', 'B'].flatMap((base) => [base, `${base}2`, `${base}'`]);
const FACE_COLORS: Color[] = ['W', 'Y', 'G', 'R', 'B', 'O'];
const SOLVED: Facelets = FACE_COLORS.flatMap((color) => new Array<Color>(9).fill(color));
const PAIRS: [Color, Color][] = [['G', 'R'], ['G', 'O'], ['B', 'O'], ['B', 'R']];

function distancesFor(pairColors: [Color, Color]): number[] {
  const distances = new Array<number>(CORNER_PLACEMENTS * EDGE_PLACEMENTS).fill(SEARCH_DEPTH + 1);
  const seen = new Set([SOLVED.join('')]);
  let frontier = [SOLVED];

  for (let depth = 1; depth <= SEARCH_DEPTH; depth++) {
    const next: Facelets[] = [];
    for (const state of frontier) {
      for (const token of SEARCH_TOKENS) {
        const moved = applyMove(state, token);
        const key = moved.join('');
        if (seen.has(key)) continue;
        seen.add(key);
        next.push(moved);

        const index = crossSolved(moved) ? topLayerPlacementIndex(moved, pairColors) : null;
        if (index !== null && distances[index] > depth) distances[index] = depth;
      }
    }
    frontier = next;
  }

  return distances;
}

const [distances, ...otherSlots] = PAIRS.map(distancesFor);
const mismatched = otherSlots.findIndex((other) => other.join() !== distances.join());
if (mismatched >= 0) throw new Error(`slot for ${PAIRS[mismatched + 1].join('')} disagrees with ${PAIRS[0].join('')}`);

const rows = Array.from({ length: CORNER_PLACEMENTS }, (_, row) =>
  `  ${distances.slice(row * EDGE_PLACEMENTS, (row + 1) * EDGE_PLACEMENTS).join(', ')},`,
);
const source = `// generated by \`pnpm f2l-pair-distances\`.

export const PAIR_SEARCH_DEPTH = ${SEARCH_DEPTH};

// rows are corner placements and columns are edge placements, both measured from the home slot.
// ${SEARCH_DEPTH + 1} means more than ${SEARCH_DEPTH} moves.
export const PAIR_DISTANCES: readonly number[] = [
${rows.join('\n')}
];
`;

fs.writeFileSync(OUTPUT_PATH, source);
const counts = distances.reduce<Record<number, number>>((acc, d) => ({ ...acc, [d]: (acc[d] ?? 0) + 1 }), {});
console.log(`Wrote ${distances.length} placements to ${path.relative(process.cwd(), OUTPUT_PATH)}`, counts);
